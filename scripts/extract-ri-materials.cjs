#!/usr/bin/env node
/**
 * Extracts text from RI source PDFs in public/ri-materials/
 * and writes lib/ri/embeddedMaterials.ts for use by grounding.
 * Run: node scripts/extract-ri-materials.cjs
 */
const fs = require('fs');
const path = require('path');
const pdf = require('pdf-parse');

const MATERIALS_DIR = path.join(__dirname, '..', 'public', 'ri-materials');
const OUTPUT_FILE = path.join(__dirname, '..', 'lib', 'ri', 'embeddedMaterials.ts');

const FILES = [
  { file: 'Help Desk Intake Form 2026.pdf', title: 'Eviction Help Desk Intake Form 2026' },
  { file: 'RILS Handout for EHD.pdf', title: 'RILS Eviction Help Desk Handout' },
  { file: 'Landlord Tenant Handbook 2024.pdf', title: 'Rhode Island Landlord-Tenant Handbook 2024' },
];

function escapeForTs(str) {
  return str
    .replace(/\\/g, '\\\\')
    .replace(/`/g, '\\`')
    .replace(/\${/g, '\\${');
}

async function main() {
  const results = [];
  for (const { file, title } of FILES) {
    const filePath = path.join(MATERIALS_DIR, file);
    if (!fs.existsSync(filePath)) {
      console.warn('Skip (not found):', file);
      continue;
    }
    const dataBuffer = fs.readFileSync(filePath);
    const data = await pdf(dataBuffer);
    const text = (data.text || '').trim().replace(/\s+/g, ' ');
    results.push({ title, text });
    console.log(`Extracted ${data.numpages} pages from ${file} (${text.length} chars)`);
  }
  const ts = `/**
 * Pre-extracted text from Rhode Island source materials.
 * Generated by: node scripts/extract-ri-materials.cjs
 * Source PDFs: public/ri-materials/
 */
export const EMBEDDED_MATERIALS = [
${results.map(({ title, text }) => `  { title: ${JSON.stringify(title)}, extractedText: \`${escapeForTs(text)}\` },`).join('\n')}
] as const;
`;
  fs.writeFileSync(OUTPUT_FILE, ts, 'utf8');
  console.log('Wrote', OUTPUT_FILE);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
